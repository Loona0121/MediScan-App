import 'dart:io';

import 'package:flutter/material.dart';
import 'package:path_provider/path_provider.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import 'package:share_plus/share_plus.dart';

class ReportService {
  static Future<void> generatePDF({
    required List<Map<String, dynamic>> inventory,
    required String reportType,
  }) async {
    final pdf = pw.Document();

    final total = inventory.length;

    final safe = inventory.where((item) {
      return item['status'] == 'SAFE';
    }).length;

    final warning = inventory.where((item) {
      return item['status'] == 'WARNING';
    }).length;

    final expired = inventory.where((item) {
      return item['status'] == 'EXPIRED';
    }).length;

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),

        build: (context) => [

          _header(reportType),

          pw.SizedBox(height: 20),

          _summaryCard(
            total,
            safe,
            warning,
            expired,
          ),

          pw.SizedBox(height: 24),

          _inventoryTable(inventory),

          pw.SizedBox(height: 20),

          pw.Divider(),

          pw.Align(
            alignment: pw.Alignment.centerRight,
            child: pw.Text(
              "Generated by MediScan",
              style: const pw.TextStyle(
                fontSize: 10,
              ),
            ),
          ),
        ],
      ),
    );

    final dir = await getTemporaryDirectory();

    final file = File(
      "${dir.path}/Inventory_Report.pdf",
    );

    await file.writeAsBytes(
      await pdf.save(),
    );

    await Printing.layoutPdf(
      onLayout: (format) async => pdf.save(),
    );

    await SharePlus.instance.share(
      ShareParams(
        files: [XFile(file.path)],
        text: "MediScan Inventory Report",
      ),
    );
  }

  static pw.Widget _header(String reportType) {
    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [

        pw.Text(
          "MEDISCAN",
          style: pw.TextStyle(
            fontSize: 28,
            fontWeight: pw.FontWeight.bold,
            color: PdfColors.blue700,
          ),
        ),

        pw.SizedBox(height: 4),

        pw.Text(
          "Inventory Report",
          style: pw.TextStyle(
            fontSize: 18,
            fontWeight: pw.FontWeight.bold,
          ),
        ),

        pw.SizedBox(height: 10),

        pw.Text(
          "Generated: ${DateTime.now()}",
        ),

        pw.Text(
          "Report Type: $reportType",
        ),

        pw.Divider(),
      ],
    );
  }

  static pw.Widget _summaryCard(
    int total,
    int safe,
    int warning,
    int expired,
  ) {
    return pw.Container(
      padding: const pw.EdgeInsets.all(18),

      decoration: pw.BoxDecoration(
        border: pw.Border.all(
          color: PdfColors.grey400,
        ),

        borderRadius: pw.BorderRadius.circular(8),
      ),

      child: pw.Row(
        mainAxisAlignment: pw.MainAxisAlignment.spaceAround,

        children: [

          _summaryItem(
            "Total",
            total.toString(),
          ),

          _summaryItem(
            "Safe",
            safe.toString(),
          ),

          _summaryItem(
            "Warning",
            warning.toString(),
          ),

          _summaryItem(
            "Expired",
            expired.toString(),
          ),
        ],
      ),
    );
  }

  static pw.Widget _summaryItem(
    String title,
    String value,
  ) {
    return pw.Column(
      children: [

        pw.Text(
          value,
          style: pw.TextStyle(
            fontSize: 20,
            fontWeight: pw.FontWeight.bold,
          ),
        ),

        pw.SizedBox(height: 4),

        pw.Text(title),
      ],
    );
  }

  static pw.Widget _inventoryTable(
    List<Map<String, dynamic>> inventory,
  ) {
    return pw.TableHelper.fromTextArray(
      headerStyle: pw.TextStyle(
        fontWeight: pw.FontWeight.bold,
        color: PdfColors.white,
      ),

      headerDecoration: const pw.BoxDecoration(
        color: PdfColors.blue700,
      ),

      cellAlignment: pw.Alignment.centerLeft,

      headers: const [
        "Medicine",
        "Category",
        "Expiry",
        "Status",
      ],

      data: inventory.map((item) {

        return [

          item["product_name"] ?? "",

          item["category"] ?? "",

          item["expiry_date"] ?? "",

          item["status"] ?? "",
        ];

      }).toList(),
    );
  }
}